#!/usr/bin/env python3
"""Generates every app icon from branding/ (see branding/README.md).

Run on the maintainer machine after changing branding/*; the results are committed, builds don't
run this. Needs ImageMagick 7 (`magick`, with SVG support) on the host.

    tool/make_icons.py                 # writes the icons into app/
    tool/make_icons.py --preview DIR   # also a preview sheet (masks, themed colours, small sizes)
"""

import argparse
import re
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BRANDING = ROOT / 'branding'
SOURCE = BRANDING / 'icon-source.jpg'
RES = ROOT / 'app/android/app/src/main/res'

# Geometry of icon-source.jpg (2048 px), measured once: the dark rounded square and the hourglass
# centre, which is also the origin of the SVG coordinates.
SQUARE = (256, 257, 1536)  # x, y, size
SQUARE_RADIUS = 320
CENTRE = (1024, 1028)
BACKGROUND = '#24242A'  # the square's colour beside the hourglass
# Colour-to-alpha threshold for the adaptive foreground: a little above BACKGROUND, because the
# square brightens towards its rim. (0-1 per channel.)
BACKGROUND_CUT = (50 / 255, 50 / 255, 58 / 255)
# Android 12+: the adaptive icon's background follows the wallpaper (dark accent tone, so the glow
# still reads); older versions keep BACKGROUND.
DYNAMIC_BACKGROUND = '@android:color/system_accent1_800'

# Android adaptive icon: 108 dp canvas; the hourglass (with its outline) has to stay inside the
# 72 dp visible circle (corners are rounded, so the glow may touch it): its half diagonal
# (733 source px) maps to 35 dp.
DP_PER_PX = 35 / 733
DENSITIES = {'mdpi': 1, 'hdpi': 1.5, 'xhdpi': 2, 'xxhdpi': 3, 'xxxhdpi': 4}

# The icon's colour gradient, from the hourglass's top-left to its bottom-right corner (the
# original runs orange -> pink -> purple). Palette "Aurora", chosen by the user on 2026-11-08 from
# four turquoise proposals.
GRADIENT = ['#34D399', '#22D3EE', '#3B82F6']
ACCENT = '#22D3EE'  # one colour for the 16/24 px desktop icon
HOURGLASS_BOX = (600, 450, 1445, 1600)  # in the source, for the gradient's direction


def magick(*args):
    subprocess.run(['magick', *map(str, args)], check=True)


def svg_shapes(svg):
    """(kind, attributes) for each <path>/<circle> of [svg], with the inherited group style."""
    text = (BRANDING / svg).read_text()
    shapes = []
    style = {}
    for tag in re.finditer(r'<(/?)(g|path|circle)\b([^>]*?)(/?)>', text):
        closing, name, attrs, selfclose = tag.groups()
        if name == 'g':
            style = {} if closing else dict(re.findall(r'([\w-]+)="([^"]*)"', attrs))
            continue
        a = {**style, **dict(re.findall(r'([\w-]+)="([^"]*)"', attrs))}
        shapes.append((name, a))
    return shapes


def vector_drawable(svg, size_dp, scale, comment):
    """An Android VectorDrawable (white) of [svg], centred on a [size_dp] canvas."""
    half = size_dp / 2
    body = []
    for kind, a in svg_shapes(svg):
        if kind == 'circle':
            cx, cy, r = (float(a[k]) for k in ('cx', 'cy', 'r'))
            d = f'M{cx - r},{cy}a{r},{r} 0 1,0 {2 * r},0a{r},{r} 0 1,0 {-2 * r},0Z'
        else:
            d = a['d']
        if a.get('fill', '#000') != 'none':
            body.append(f'        <path android:fillColor="#FFFFFFFF" android:pathData="{d}"/>')
        else:
            body.append(
                '        <path android:strokeColor="#FFFFFFFF" '
                f'android:strokeWidth="{a["stroke-width"]}" android:strokeLineJoin="round" '
                f'android:pathData="{d}"/>'
            )
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} Generated by tool/make_icons.py from branding/{svg}; don't edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size_dp}dp"
    android:height="{size_dp}dp"
    android:viewportWidth="{size_dp}"
    android:viewportHeight="{size_dp}">
    <group android:translateX="{half}" android:translateY="{half}"
        android:scaleX="{scale:.6f}" android:scaleY="{scale:.6f}">
{chr(10).join(body)}
    </group>
</vector>
'''


def rounded_square(tmp, source):
    """The source's dark square without the white page and shadow: transparent corners."""
    out = tmp / 'square.png'
    x, y, size = SQUARE
    magick(
        source, '-crop', f'{size}x{size}+{x}+{y}', '+repage',
        '(', '-size', f'{size}x{size}', 'xc:black', '-fill', 'white',
        '-draw', f'roundrectangle 0,0 {size - 1},{size - 1} {SQUARE_RADIUS},{SQUARE_RADIUS}', ')',
        '-alpha', 'off', '-compose', 'CopyOpacity', '-composite', out,
    )
    return out


def recoloured_source(tmp):
    """The source with the hourglass in GRADIENT instead of its own colours: brightness from the
    original (glow, grains, glass), colour from a diagonal gradient. Darks stay neutral, midtones
    take the gradient, highlights go towards white. A plain hue shift can't do this: it would turn
    orange -> purple into green -> red, not green -> blue."""
    out = tmp / 'source-recoloured.png'
    luma = tmp / 'luma.png'
    magick(SOURCE, '-colorspace', 'gray', '-colorspace', 'sRGB', '-define', 'png:color-type=2', luma)
    x0, y0, x1, y1 = HOURGLASS_BOX
    scale = 4  # the gradient is smooth: compute it at a quarter size
    size = 2048 // scale
    gradient = tmp / 'gradient.png'
    magick(
        '-size', f'{size}x{size}', 'xc:',
        '-fx', f'pos=((i+j)*{scale}-{x0 + y0})/{(x1 + y1) - (x0 + y0)}; pos<0?0:(pos>1?1:pos)',
        '(', '-size', '1x1', *['xc:' + c for c in GRADIENT], '+append',
        '-filter', 'Triangle', '-resize', '256x1!', ')', '-clut',
        '-resize', '2048x2048!', '-colorspace', 'sRGB', gradient,
    )
    magick(
        luma,
        # the gradient, as bright as the original there
        '(', gradient, '(', luma, '-level', '0%,48%', ')', '-compose', 'Multiply', '-composite', ')',
        # where: midtones and up (not the dark background)
        '(', luma, '-level', '18%,55%', '-colorspace', 'gray', ')',
        '-compose', 'Over', '-composite',
        '(', luma, '-level', '68%,100%', ')', '-compose', 'Screen', '-composite',
        '-define', 'png:color-type=2', out,
    )
    return out


def small_desktop(tmp, px):
    """Desktop icon for 16–24 px: the small hourglass in ACCENT on the dark rounded square."""
    out = tmp / f'small-{px}.png'
    big = 256
    radius = big * SQUARE_RADIUS // SQUARE[2]
    magick(
        '-size', f'{big}x{big}', 'xc:none', '-fill', BACKGROUND,
        '-draw', f'roundrectangle 0,0 {big - 1},{big - 1} {radius},{radius}',
        '(', '-background', 'none', '-density', 96, BRANDING / 'hourglass-small.svg',
        '-fill', ACCENT, '-colorize', '100', '-resize', f'x{int(big * 0.8)}', ')',
        '-gravity', 'center', '-composite', '-resize', f'{px}x{px}', out,
    )
    return out


def medium_desktop(tmp, px):
    """Desktop icon for 32–64 px (taskbar, tray at higher scaling): the detailed hourglass blurs
    into the dark square there (user 2026-11-10), so the bold small hourglass in GRADIENT with a
    soft glow, on the dark rounded square."""
    out = tmp / f'medium-{px}.png'
    big = 256
    radius = big * SQUARE_RADIUS // SQUARE[2]
    shape, gradient, hourglass = (tmp / f'medium-{n}.png' for n in ('shape', 'gradient', 'fill'))
    magick(
        '-background', 'none', '-density', 96, BRANDING / 'hourglass-small.svg',
        '-alpha', 'extract', '-resize', f'x{int(big * 0.86)}',
        '-gravity', 'center', '-background', 'black', '-extent', f'{big}x{big}', shape,
    )
    magick('-size', '1x1', *['xc:' + c for c in GRADIENT], '+append', '-filter', 'Triangle',
           '-resize', f'{big}x{big}!', '-distort', 'SRT', '45', gradient)
    magick(gradient, shape, '-alpha', 'off', '-compose', 'CopyOpacity', '-composite', hourglass)
    magick(
        '-size', f'{big}x{big}', 'xc:none', '-fill', BACKGROUND,
        '-draw', f'roundrectangle 0,0 {big - 1},{big - 1} {radius},{radius}',
        '(', hourglass, '-channel', 'A', '-blur', '0x10', '-evaluate', 'multiply', '0.8',
        '+channel', ')', '-compose', 'Screen', '-composite',
        hourglass, '-compose', 'Over', '-composite', '-resize', f'{px}x{px}', out,
    )
    return out


def foreground(tmp, source):
    """The adaptive icon's foreground at 432 px (xxxhdpi): the hourglass with its glow on a
    transparent background, so any background colour shows through (Android 12+ uses the
    wallpaper's). The dark square is taken out as colour-to-alpha: a pixel's alpha is how far it
    rises above BACKGROUND_CUT, its colour what it was before being laid over that. The edge of the
    crop fades out softly."""
    out = tmp / 'foreground.png'
    region = 1400  # around CENTRE; stays inside the rounded square including the feather
    cx, cy = CENTRE
    canvas = round(108 / DP_PER_PX)  # source px that the 108 dp canvas covers
    crop, alpha, colour = tmp / 'fg-crop.png', tmp / 'fg-alpha.png', tmp / 'fg-colour.png'
    magick(source, '-crop', f'{region}x{region}+{cx - region // 2}+{cy - region // 2}', '+repage',
           crop)
    r, g, b = BACKGROUND_CUT
    magick(
        crop, '-fx',
        f'al=max(max((u.r-{r})/{1 - r},(u.g-{g})/{1 - g}),(u.b-{b})/{1 - b}); clamp(al)',
        '-colorspace', 'gray',
        '(', '-size', f'{region}x{region}', 'xc:black', '-fill', 'white',
        '-draw', f'roundrectangle 110,110 {region - 111},{region - 111} 400,400',
        '-blur', '0x55', ')',
        '-compose', 'Multiply', '-composite', alpha,
    )
    magick(crop, alpha, '-fx',
           f'bk=channel({r},{g},{b},0,0); al=max(v.r,0.004); clamp((u-bk*(1-al))/al)', colour)
    magick(
        colour, alpha, '-alpha', 'off', '-compose', 'CopyOpacity', '-composite', '-compose', 'Over',
        '-background', 'none', '-gravity', 'center', '-extent', f'{canvas}x{canvas}',
        '-resize', '432x432', out,
    )
    return out


def write_android(tmp, source):
    fg = foreground(tmp, source)
    square = rounded_square(tmp, source)
    for name, factor in DENSITIES.items():
        folder = RES / f'mipmap-{name}'
        folder.mkdir(exist_ok=True)
        magick(fg, '-resize', f'{round(108 * factor)}x', folder / 'ic_launcher_foreground.png')
        # Android < 8 shows the icon as it is: the rounded square.
        magick(square, '-resize', f'{round(48 * factor)}x', folder / 'ic_launcher.png')
    (RES / 'drawable/ic_launcher_monochrome.xml').write_text(vector_drawable(
        'hourglass.svg', 108, DP_PER_PX,
        'Themed icon (Android 13+): the system tints this in the wallpaper colours.',
    ))
    (RES / 'drawable/ic_quick.xml').write_text(vector_drawable(
        'hourglass-small.svg', 24, 22 / 1280,
        'Hourglass for notification, Quick Settings tile and update notice.',
    ))
    (RES / 'values/ic_launcher_background.xml').write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_icons.py. -->
<resources>
    <color name="ic_launcher_background">{BACKGROUND}</color>
</resources>
''')
    (RES / 'values-v31').mkdir(exist_ok=True)
    (RES / 'values-v31/ic_launcher_background.xml').write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_icons.py. Android 12+: a dark tone of the wallpaper colours. -->
<resources>
    <color name="ic_launcher_background">{DYNAMIC_BACKGROUND}</color>
</resources>
''')
    return fg, square


def write_desktop(tmp, square):
    big = square  # one icon everywhere
    linux = ROOT / 'app/linux/runner/resources'
    linux.mkdir(parents=True, exist_ok=True)
    magick(big, '-resize', '512x512', linux / 'app_icon.png')
    win256 = tmp / 'win-256.png'
    magick(big, '-resize', '256x256', win256)
    sizes = [win256, *(medium_desktop(tmp, px) for px in (64, 48, 32))]
    sizes += [small_desktop(tmp, 24), small_desktop(tmp, 16)]
    magick(*sizes, ROOT / 'app/windows/runner/resources/app_icon.ico')
    # The tray icon while clocked out (docs/specs/work-pc.md §3): grey and a little faded.
    idle = []
    for size in sizes:
        out = size.with_name(f'{size.stem}-idle.png')
        magick(size, '-colorspace', 'Gray', '-channel', 'A', '-evaluate', 'multiply', '0.7',
               '+channel', f'PNG32:{out}')
        idle.append(out)
    magick(*idle, ROOT / 'app/windows/runner/resources/app_icon_idle.ico')
    return big


def preview(tmp, fg, square, big, out_dir):
    """Masks, themed colours and small sizes on one sheet."""
    out_dir.mkdir(parents=True, exist_ok=True)
    tiles = []
    # Masks on BACKGROUND, then circles on a few wallpaper tones (system_accent1_800 of a blue,
    # green, red and purple wallpaper).
    for name, draw, bg in [
        ('circle', 'circle 216,216 216,0', BACKGROUND),
        ('squircle', 'roundrectangle 0,0 431,431 150,150', BACKGROUND),
        ('square', 'roundrectangle 0,0 431,431 40,40', BACKGROUND),
        *[(f'circle-{c}', 'circle 216,216 216,0', c)
          for c in ('#0B3058', '#1F3A1A', '#5A1B17', '#3B2464')],
    ]:
        tile = tmp / f'mask-{name}.png'
        magick(
            '-size', '432x432', f'xc:{bg}', fg, '-composite',
            '(', '-size', '432x432', 'xc:black', '-fill', 'white', '-draw', draw, ')',
            '-alpha', 'off', '-compose', 'CopyOpacity', '-composite', '-compose', 'Over',
            '-background', '#E8EAED', '-flatten', '-resize', '216x216', tile,
        )
        tiles.append(tile)
    for name, bg, fg_colour in [('themed-light', '#D3E8D3', '#0F3A1E'),
                                ('themed-dark', '#1E2B3C', '#B7D0F0')]:
        tile = tmp / f'{name}.png'
        magick(
            '-size', '432x432', f'xc:{bg}',
            '(', '-background', 'none', '-density', 48, BRANDING / 'hourglass.svg',
            '-fill', fg_colour, '-colorize', '100', '-resize', 'x229', ')',
            '-gravity', 'center', '-composite',
            '(', '-size', '432x432', 'xc:black', '-fill', 'white',
            '-draw', 'circle 216,216 216,0', ')',
            '-alpha', 'off', '-compose', 'CopyOpacity', '-composite', '-compose', 'Over',
            '-background', '#E8EAED', '-flatten', '-resize', '216x216', tile,
        )
        tiles.append(tile)
    row1 = tmp / 'row1.png'
    magick('montage', *tiles, '-tile', 'x1', '-geometry', '+8+8', '-background', '#E8EAED', row1)
    sizes = []
    t = tmp / 'p-256.png'
    magick(big, '-resize', '256x256', t)
    sizes += [t, medium_desktop(tmp, 48), medium_desktop(tmp, 32)]
    for px in (24, 16):
        sizes.append(small_desktop(tmp, px))
    orig = tmp / 'orig-256.png'
    magick(square, '-resize', '256x256', orig)
    bar = tmp / 'statusbar.png'
    magick(
        '-size', '160x48', 'xc:#101418',
        '(', '-background', 'none', '-density', 24, BRANDING / 'hourglass-small.svg',
        '-fill', 'white', '-colorize', '100', '-resize', 'x24', ')',
        '-gravity', 'west', '-geometry', '+16+0', '-composite', bar,
    )
    row2 = tmp / 'row2.png'
    magick('montage', orig, *sizes, bar, '-tile', 'x1', '-geometry', '+8+8',
           '-background', '#E8EAED', row2)
    magick(row1, row2, '-background', '#E8EAED', '-gravity', 'west', '-append',
           out_dir / 'icon-preview.png')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--preview', type=Path)
    args = parser.parse_args()
    with tempfile.TemporaryDirectory() as t:
        tmp = Path(t)
        source = recoloured_source(tmp)
        fg, square = write_android(tmp, source)
        big = write_desktop(tmp, square)
        if args.preview:
            preview(tmp, fg, square, big, args.preview)


if __name__ == '__main__':
    main()
